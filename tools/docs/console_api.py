"""Generates the DebugConsole's typed API table from the reference docs.

The signature block (the first ```lua block under each heading) of docs/reference/h7.md, mod.md and objects.md
holds lines like `h7.first(class: string | Class) → Object?`. They become
dist/mods/DebugConsole/api.lua, which the console uses for its suggestions and parameter hints, so the docs
stay the single source of the API's types.

    python tools/docs/console_api.py          # write api.lua
    python tools/docs/console_api.py --check  # exit 1 if api.lua is out of date (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ["docs/reference/h7.md", "docs/reference/mod.md", "docs/reference/objects.md"]
OUT = ROOT / "dist/mods/DebugConsole/api.lua"

SIGNATURE = re.compile(r"^(?P<callee>[A-Za-z_][\w.:]*)\((?P<params>.*)\)\s*(?:→\s*(?P<ret>.+))?$")


def split_params(text):
    """Splits at top-level commas (types like `function(self, args)` contain commas)."""
    out, depth, cur, quote = [], 0, "", None
    for c in text:
        if quote:
            cur += c
            if c == quote:
                quote = None
            continue
        if c in "\"'":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def plain(md):
    """Markdown to plain text: links keep their text, code marks and emphasis go."""
    md = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", md)
    return md.replace("`", "").replace("**", "")


def summary(lines, i):
    """First sentence of the paragraph starting at lines[i] (after blank lines)."""
    while i < len(lines) and not lines[i].strip():
        i += 1
    para = []
    while i < len(lines) and lines[i].strip() and not lines[i].startswith(("#", "|", "```", "-")):
        para.append(lines[i].strip())
        i += 1
    text = plain(" ".join(para))
    m = re.match(r"(.+?[.:])(\s|$)", text)
    text = m.group(1) if m else text
    return text if len(text) <= 140 else text[:137] + "..."


def parse():
    entries = {}
    for rel in SOURCES:
        lines = (ROOT / rel).read_text(encoding="utf-8").splitlines()
        i, after_heading = 0, False
        while i < len(lines):
            line = lines[i]
            if line.startswith("#"):
                after_heading = True
            elif line.strip() == "```lua" and after_heading:
                after_heading = False
                j = i + 1
                block = []
                while j < len(lines) and lines[j].strip() != "```":
                    block.append(lines[j].strip())
                    j += 1
                doc = summary(lines, j + 1)
                for sig in block:
                    m = SIGNATURE.match(sig)
                    if not m:
                        continue
                    params = split_params(m.group("params"))
                    if any(not re.match(r"^(\.\.\.|[A-Za-z_]\w*)\??:\s*\S", p) for p in params):
                        continue  # an example call, not a typed signature
                    entries.setdefault(m.group("callee"), []).append(
                        {"params": params, "ret": (m.group("ret") or "").strip(), "doc": doc})
                i = j
            elif line.strip().startswith("```"):
                after_heading = False
            i += 1
    return entries


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries):
    out = ["-- Generated by tools/docs/console_api.py from " + ", ".join(SOURCES) + ". Do not edit:",
           "-- change the signature lines in the docs and run the script again.",
           "-- [callee] = { overload, ... }; overload = { params = { \"name: type\", ... }, ret = \"type\", doc = \"...\" }",
           "return {"]
    for callee in sorted(entries):
        overloads = []
        for o in entries[callee]:
            params = ", ".join(lua_str(p) for p in o["params"])
            overloads.append("{ params = { %s }, ret = %s, doc = %s }" % (params, lua_str(o["ret"]), lua_str(o["doc"])))
        out.append("    [%s] = {" % lua_str(callee))
        for o in overloads:
            out.append("        %s," % o)
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = render(parse())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python tools/docs/console_api.py")
            return 1
        print("api.lua is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10)) - 5} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
